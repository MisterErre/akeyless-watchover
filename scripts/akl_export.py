class CliSource:
    def __init__(self, binary: str, profile: str | None):
        self.binary, self.profile = binary, profile

    def call(self, *args: str, allow_fail: bool = False):
        cmd = [self.binary, *args, "--json"] + (["--profile", self.profile] if self.profile else [])
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            if allow_fail:
                return None
            raise RuntimeError(f"{' '.join(cmd)}: {(res.stderr or res.stdout).strip()}")
        return json.loads(res.stdout or "null")

    def _paged(self, command: str, key: str, *extra: str) -> list:
        out, token = [], None
        while True:
            data = self.call(command, *extra, *(["--pagination-token", token] if token else [])) or {}
            out += data.get(key) or []
            token = data.get("next_page")
            if not token:
                return out

    def roles(self):
        return [self.call("get-role", "--name", r["role_name"]) for r in self._paged("list-roles", "roles")]

    def auth_methods(self):
        return [self.call("get-auth-method", "--name", m["auth_method_name"])
                for m in self._paged("list-auth-methods", "auth_methods")]

    def walk(self, root: str, max_depth: int):
        """BFS over list-items: returns (folder paths, items)."""
        seen, items, queue = set(), {}, [(root.rstrip("/") or "/", 0)]
        while queue:
            path, depth = queue.pop(0)
            data = self.call("list-items", "--path", path) or {}
            for it in data.get("items") or []:
                items[it.get("item_name")] = it
            for f in data.get("folders") or []:
                f = "/" + f.strip("/")
                if f not in seen and f != path:
                    seen.add(f)
                    if depth + 1 < max_depth:
                        queue.append((f, depth + 1))
        return sorted(seen), list(items.values())

    def folder(self, name: str):
        out = self.call("folder", "get", "--name", name, allow_fail=True)
        return (out or {}).get("folder") if isinstance(out, dict) else None

    def describe(self, name: str):
        return self.call("describe-item", "--name", name, allow_fail=True)

    def custom_fields(self):
        return self.call("account-custom-field", "list", allow_fail=True) or []

    def policies(self):
        return (self.call("policy", "list", allow_fail=True) or {}).get("policies") or []

    def account_settings(self):
        return self.call("get-account-settings", allow_fail=True)


class DirSource:
    """Replays a raw/ directory written by a previous export (or hand-made fixtures)."""

    def __init__(self, d: str):
        self.d = d

    def _many(self, sub):
        return [json.load(open(f)) for f in sorted(glob.glob(os.path.join(self.d, sub, "*.json")))]

    def _one(self, name, default):
        p = os.path.join(self.d, name)
        return json.load(open(p)) if os.path.exists(p) else default

    def roles(self):
        return self._many("roles")

    def auth_methods(self):
        return self._many("auth_methods")

    def walk(self, root, max_depth):
        folders = self._one("folders_discovered.json", [])
        return [f for f in folders if f.startswith(root.rstrip("/") + "/") or root == "/"], self._many("items")

    def folder(self, name):
        for f in self._many("folders"):
            if (f.get("folder") or {}).get("folder_name", "").rstrip("/") == name.rstrip("/"):
                return f["folder"]
        return None

    def describe(self, name):
        for it in self._many("items"):
            if it.get("item_name") == name:
                return it
        return None

    def custom_fields(self):
        return self._one("custom_fields.json", [])

    def policies(self):
        return self._one("policies.json", {}).get("policies") or []

    def account_settings(self):
        return self._one("account_settings.json", None)


# ------------------------------------------------------------------ helpers
def redact(obj, path=""):
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            p = f"{path}.{k}" if path else k
            if (k in SECRET_KEYS or p.endswith("api_key_access_rules.key")) and v not in (None, "", []):
                out[k] = "<redacted>"
            else:
                out[k] = redact(v, p)
        return out
    if isinstance(obj, list):
        return [redact(v, path) for v in obj]
    return obj


def fname(name: str) -> str:
    return (re.sub(r"[^A-Za-z0-9_.-]", "_", name.strip("/")) or "root") + ".json"


def tf_id(prefix: str, name: str, used: set) -> str:
    base = re.sub(r"[^A-Za-z0-9_]", "_", name.strip("/")).strip("_").lower() or "root"
    base = f"{prefix}_{base}" if not base[0].isalpha() else base
    cand, i = base, 2
    while cand in used:
        cand, i = f"{base}_{i}", i + 1
    used.add(cand)
    return cand


def hcl(s: str) -> str:
    return json.dumps(s)


def am_type(am: dict) -> tuple[str | None, str]:
    info = am.get("access_info") or {}
    for key, (t, _) in AM_RULES.items():
        if info.get(key):
            return t, key
    for key in OTHER_AM_RULES:
        if info.get(key):
            return None, key
    rt = str(info.get("rules_type") or "").lower().replace("-", "_")
    for key, (t, _) in AM_RULES.items():
        if rt == t:
            return t, key
    return None, rt or "unknown"


def is_pki_issuer(item: dict) -> bool:
    gi = item.get("item_general_info") or {}
    cid = gi.get("cert_issue_details") or item.get("certificate_issue_details") or {}
    it = str(item.get("item_type", "")).upper()
    return bool(cid.get("pki_cert_issuer_details")) or ("PKI" in it and "ISSUER" in it)


