def convert_role(role: dict, report: list[str]) -> dict:
    name = role["role_name"]
    r: dict = {}
    if role.get("description") or role.get("comment"):
        r["description"] = role.get("description") or role.get("comment")
    if str(role.get("delete_protection", "")).lower() == "true":
        r["delete_protection"] = True
    rules = []
    for pr in ((role.get("rules") or {}).get("path_rules") or []):
        rtype, path, caps = pr.get("type"), pr.get("path"), list(pr.get("capabilities") or [])
        if rtype in ACCESS_RULES:
            attr = ACCESS_RULES[rtype]
            if path in ACCESS_PATH:
                r[attr] = ACCESS_PATH[path]
            elif rtype == "event-forwarder-rule":
                r.setdefault("event_forwarders_name", []).append(path)
            else:
                report.append(f"- role `{name}`: access rule {rtype} with unexpected path `{path}` - review")
            continue
        if rtype not in RULE_TYPES:
            report.append(f"- role `{name}`: rule type `{rtype}` on `{path}` is not handled by the model - review")
            continue
        if pr.get("ttl"):
            report.append(f"- role `{name}`: temporary rule on `{path}` (ttl) skipped - temporary rules are CLI-only")
            continue
        if rtype == "sra-rule":
            caps = [SRA_CAPS.get(c, c) for c in caps]
        rule = {"path": path, "capabilities": sorted(caps)}
        if rtype != "item-rule":
            rule["type"] = rtype
        rules.append(rule)
        if path in ("/*", "/") and set(caps) - {"list", "deny"} and not (
                rtype in ("role-rule", "auth-method-rule") and set(caps) <= {"list", "read", "deny"}):
            r["allow_root_scope"] = True
            report.append(f"- role `{name}`: root-scope rule `{rtype} {path} {caps}` - confirm it is intended")
    r["rules"] = rules
    assocs = []
    for a in role.get("role_auth_methods_assoc") or []:
        entry = {"auth_method": a.get("auth_method_name")}
        sc = a.get("auth_method_sub_claims") or {}
        if sc:
            entry["sub_claims"] = {k: (v if isinstance(v, list) else [v]) for k, v in sc.items()}
        if a.get("sub_claims_case_sensitive") is False:
            entry["case_sensitive"] = False
        if a.get("is_subclaims_with_operator"):
            report.append(f"- role `{name}` <- `{entry['auth_method']}`: sub-claims use AND/OR operators - check the exported value")
        assocs.append(entry)
    if assocs:
        r["associations"] = assocs
    return r


def convert_am(am: dict, report: list[str]) -> dict:
    name = am["auth_method_name"]
    info = am.get("access_info") or {}
    t, key = am_type(am)
    if t is None:
        report.append(f"- auth method `{name}`: type `{key}` is not modelled - manage it outside the model, "
                      "or use --hcl to get plain Terraform for it")
        return {"type": f"TODO-unsupported-{key}"}
    a: dict = {"type": t}
    if am.get("description"):
        a["description"] = am["description"]
    for src, dst in AM_RULES[key][1].items():
        v = (info.get(key) or {}).get(src)
        if v not in (None, "", []):
            a[dst] = v
    if t == "oidc":
        a["client_secret_var"] = re.sub(r"[^a-z0-9]+", "_", name.strip("/").lower()) + "_client_secret"
        report.append(f"- auth method `{name}`: client secret not exported - put it in TF_VAR_auth_method_secrets "
                      f"under `{a['client_secret_var']}`")
    if info.get("access_expires"):
        a["access_expires"] = info["access_expires"]
    if info.get("cidr_whitelist"):
        a["bound_ips"] = [c.strip() for c in str(info["cidr_whitelist"]).split(",") if c.strip()]
    if info.get("gw_cidr_whitelist"):
        a["gw_bound_ips"] = [c.strip() for c in str(info["gw_cidr_whitelist"]).split(",") if c.strip()]
    for k in ("force_sub_claims", "jwt_ttl", "audit_logs_claims", "allowed_client_type"):
        if info.get(k) not in (None, [], ""):
            a[k] = info[k]
    if t in ("oidc", "saml", "oauth2") and info.get("sub_claims_delimiters"):
        a["subclaims_delimiters"] = info["sub_claims_delimiters"]
    if str(am.get("delete_protection", "")).lower() == "true":
        a["delete_protection"] = True
    if t == "k8s":
        report.append(f"- auth method `{name}` (k8s): also needs the Gateway-side K8s auth config (out of scope)")
    if t == "api_key":
        report.append(f"- auth method `{name}`: API key - after import its access key will be in Terraform state")
    return a


def convert_folder(f: dict) -> dict:
    out: dict = {}
    if f.get("metadata"):
        out["description"] = f["metadata"]
    if f.get("tags"):
        out["tags"] = f["tags"]
    if f.get("delete_protection"):
        out["delete_protection"] = True
    return out


# ------------------------------------------------------------------ main
def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="output directory (model/, imports.tf or hcl/, raw/, REPORT.md)")
    ap.add_argument("--profile", help="akeyless CLI profile with read access to the objects to export")
    ap.add_argument("--akeyless", default="akeyless", help="path to the akeyless CLI binary")
    ap.add_argument("--from-dir", help="replay a raw/ directory of a previous export instead of calling the CLI")
    ap.add_argument("--types", default=",".join(TYPES),
                    help="comma-separated object families: " + ", ".join(TYPES))
    ap.add_argument("--only", help="keep only objects whose name matches this regex")
    ap.add_argument("--exclude", action="append", default=[], help="regex of names to skip (repeatable)")
    ap.add_argument("--root", default="/", help="folder to start the item/folder walk from")
    ap.add_argument("--max-depth", type=int, default=20, help="maximum folder depth of the walk")
    ap.add_argument("--persona-auth-method", help="keep one identity's view: its auth method ...")
    ap.add_argument("--persona-claim", action="append", default=[],
                    help="... and its claims, key=value (repeatable); keeps roles whose association matches")
    ap.add_argument("--hcl", action="store_true", help="write plain Terraform import blocks for every object (hcl/)")
    ap.add_argument("--generate", action="store_true",
                    help="with --hcl: run 'terraform plan -generate-config-out' (needs terraform and "
                         "AKEYLESS_ACCESS_ID/AKEYLESS_ACCESS_KEY in the environment)")
    ap.add_argument("--terraform", default="terraform", help="terraform or tofu binary used by --generate")
    return ap


def main(argv: list[str] | None = None) -> None:
    try:
        _main(argv)
    except (RuntimeError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        sys.exit(2)


def _main(argv: list[str] | None = None) -> None:
    a = build_parser().parse_args(argv)
    types = [t.strip() for t in a.types.split(",") if t.strip()]
    bad = set(types) - set(TYPES)
    if bad:
        raise ValueError(f"unknown --types {sorted(bad)}; valid: {', '.join(TYPES)}")
    if bool(a.persona_auth_method) != bool(a.persona_claim) and a.persona_claim:
        raise ValueError("--persona-claim needs --persona-auth-method")
    if a.generate and not a.hcl:
        raise ValueError("--generate needs --hcl")
    claims: dict = {}
    for pc in a.persona_claim:
        if "=" not in pc:
            raise ValueError(f"--persona-claim must be key=value, got {pc!r}")
        k, v = pc.split("=", 1)
        claims.setdefault(k, []).append(v)
    only = re.compile(a.only) if a.only else None
    excl = [re.compile(x) for x in a.exclude]

    def keep(n: str) -> bool:
        return (only is None or bool(only.search(n))) and not any(x.search(n) for x in excl)

    src = DirSource(a.from_dir) if a.from_dir else CliSource(a.akeyless, a.profile)
    raw = os.path.join(a.out, "raw")
    os.makedirs(raw, exist_ok=True)

    def save(sub, name, obj):
        d = os.path.join(raw, sub) if sub else raw
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, name), "w") as fh:
            json.dump(redact(obj), fh, indent=2)

    report: list[str] = []
    found: dict = {t: [] for t in TYPES}

    if "auth-methods" in types or a.persona_auth_method:
        for am in src.auth_methods():
            save("auth_methods", fname(am["auth_method_name"]), am)
            found["auth-methods"].append(am)
    if "roles" in types:
        for r in src.roles():
            save("roles", fname(r["role_name"]), r)
            found["roles"].append(r)
    folders, items = [], []
    if {"folders", "pki-issuers"} & set(types):
        folders, items = src.walk(a.root, a.max_depth)
        save("", "folders_discovered.json", folders)
        for it in items:
            if it.get("item_name"):
                save("items", fname(it["item_name"]), it)
    if "folders" in types:
        explicit = 0
        for f in folders:
            fo = src.folder(f)
            if fo:
                save("folders", fname(f), {"folder": fo})
                found["folders"].append(fo)
                explicit += 1
        report.append(f"- folders: {len(folders)} discovered, {explicit} explicit folder object(s) exported "
                      "(implicit folders exist through item paths and need no resource)")
    if "pki-issuers" in types:
        for it in items:
            itype = str(it.get("item_type", "")).upper()
            has_details = bool((it.get("item_general_info") or {}).get("cert_issue_details"))
            # describe only items whose type looks like an issuer (one CLI call each)
            full = it if has_details or not ("ISSUER" in itype or "CERT" in itype) else (src.describe(it["item_name"]) or it)
            if is_pki_issuer(full):
                found["pki-issuers"].append(full)
        types_seen = sorted({str(i.get("item_type")) for i in items})
        if items:
            report.append(f"- items walked: {len(items)} (item types: {', '.join(types_seen)}); secrets, keys and "
                          "targets are not exported - only PKI issuers")
    if "custom-fields" in types:
        cf = src.custom_fields()
        save("", "custom_fields.json", cf)
        found["custom-fields"] = cf
    if "key-policies" in types:
        pol = src.policies()
        save("", "policies.json", {"policies": pol})
        found["key-policies"] = [p for p in pol if str(p.get("type", "keys")).lower() in ("keys", "key", "")]
    if "account-settings" in types:
        acc = src.account_settings()
        if acc:
            save("", "account_settings.json", acc)
            found["account-settings"] = [acc]

    # ---- selection
    found["roles"] = [r for r in found["roles"] if keep(r["role_name"])]
    found["auth-methods"] = [m for m in found["auth-methods"] if keep(m["auth_method_name"])]
    found["folders"] = [f for f in found["folders"] if keep(f.get("folder_name", ""))]
    found["pki-issuers"] = [i for i in found["pki-issuers"] if keep(i["item_name"])]
    found["key-policies"] = [p for p in found["key-policies"] if keep(p.get("path", ""))]

    model_roles = {r["role_name"]: convert_role(r, report) for r in found["roles"]}
    if a.persona_auth_method:
        pam = "/" + a.persona_auth_method.strip("/")
        found["auth-methods"] = [m for m in found["auth-methods"] if "/" + m["auth_method_name"].strip("/") == pam]
        if not found["auth-methods"]:
            report.append(f"- persona auth method `{pam}` was not found")
        matched = {}
        for rn, r in model_roles.items():
            for asc in r.get("associations", []):
                if "/" + str(asc["auth_method"]).strip("/") == pam and \
                        sub_claims_match(asc.get("sub_claims") or {}, claims, asc.get("case_sensitive", True)):
                    matched[rn] = r
                    break
        model_roles = matched
        found["roles"] = [r for r in found["roles"] if r["role_name"] in matched]
        for t in ("folders", "custom-fields", "key-policies", "pki-issuers", "account-settings"):
            found[t] = []
        report.append(f"- persona view: auth method `{pam}` with claims {claims} -> {len(matched)} matching role(s)")

    os.makedirs(a.out, exist_ok=True)
    if a.hcl:
        write_hcl(a, found, report)
    else:
        write_model(a, found, model_roles, report)

    with open(os.path.join(a.out, "REPORT.md"), "w") as fh:
        counts = ", ".join(f"{t}: {len(v)}" for t, v in found.items() if t in types or t == "auth-methods")
        fh.write(f"# Export report\n\nmode: {'hcl' if a.hcl else 'model'}; {counts}\n\n"
                 + ("\n".join(report) if report else "Nothing needs review.") + "\n")
    print(f"exported ({'hcl' if a.hcl else 'model'}): " +
          ", ".join(f"{len(v)} {t}" for t, v in found.items() if v) + f"; {len(report)} item(s) in REPORT.md")


def write_model(a, found, model_roles, report):
    model_ams, imports = {}, []
    for am in found["auth-methods"]:
        n = am["auth_method_name"]
        model_ams[n] = convert_am(am, report)
        t = model_ams[n]["type"]
        if not t.startswith("TODO"):
            imports.append(f"import {{\n  to = akeyless_auth_method_{t}.this[{hcl(n)}]\n  id = {hcl(n)}\n}}\n")
    for n, r in model_roles.items():
        imports.append(f"import {{\n  to = akeyless_role.this[{hcl(n)}]\n  id = {hcl(n)}\n}}\n")
        for asc in r.get("associations", []):
            am = asc["auth_method"]
            if am not in model_ams:
                r["allow_external_auth_methods"] = True
                report.append(f"- role `{n}` is associated with `{am}`, which is not in this export")
            imports.append(f"import {{\n  to = akeyless_associate_role_auth_method.this[{hcl(n + '|' + am)}]\n"
                           f"  id = {hcl(n + ':' + am)}\n}}\n")
    folders = {}
    for f in found["folders"]:
        n = "/" + f["folder_name"].strip("/")
        folders[n] = convert_folder(f)
        imports.append(f"import {{\n  to = akeyless_folder.this[{hcl(n)}]\n  id = {hcl(n)}\n}}\n")
    gov: dict = {}
    for cf in found["custom-fields"]:
        key = re.sub(r"[^a-z0-9]+", "-", f"{cf['name']}-{cf.get('object_type', '')}".lower()).strip("-")
        entry = {"name": cf["name"], "object_type": cf.get("object_type")}
        if cf.get("object"):
            entry["object"] = cf["object"]
        if cf.get("required") is not None:
            entry["required"] = bool(cf["required"])
        gov.setdefault("custom_fields", {})[key] = entry
        imports.append(f"import {{\n  to = akeyless_account_custom_field.this[{hcl(key)}]\n  id = {hcl(str(cf['id']))}\n}}\n")
    for p in found["key-policies"]:
        entry = {k: p[k] for k in ("allowed_algorithms", "allowed_key_names", "allowed_key_types",
                                   "max_rotation_interval_days", "object_types") if p.get(k) not in (None, [], "")}
        gov.setdefault("key_policies", {})[p["path"]] = entry
        imports.append(f"import {{\n  to = akeyless_policy_keys.this[{hcl(p['path'])}]\n  id = {hcl(str(p['id']))}\n}}\n")
    if found["pki-issuers"]:
        report.append(f"- {len(found['pki-issuers'])} PKI issuer(s) found: model mode does not translate issuers "
                      "(nested API format). Run again with --hcl --types pki-issuers for plain Terraform, or write "
                      "pki.yaml from raw/items/")
    if found["account-settings"]:
        report.append("- account settings exported to raw/account_settings.json; use --hcl --types account-settings "
                      "for the Terraform-managed subset, and account_settings_cli for the rest")
    mdir = os.path.join(a.out, "model")
    os.makedirs(os.path.join(mdir, "roles"), exist_ok=True)
    for path, doc in ((os.path.join(mdir, "roles", "imported.yaml"), {"roles": model_roles}),
                      (os.path.join(mdir, "auth_methods.imported.yaml"), {"auth_methods": model_ams}),
                      (os.path.join(mdir, "folders.imported.yaml"), {"folders": folders}),
                      (os.path.join(mdir, "governance.imported.yaml"), gov)):
        with open(path, "w") as fh:
            yaml.safe_dump(doc, fh, sort_keys=True, width=140)
    with open(os.path.join(a.out, "imports.tf"), "w") as fh:
        fh.write("# Generated by watchover export (model mode) - addresses of terraform/*.tf.\n"
                 "# Remove after the first successful apply.\n\n" + "\n".join(imports))


def write_hcl(a, found, report):
    d = os.path.join(a.out, "hcl")
    os.makedirs(d, exist_ok=True)
    used: dict = {}
    blocks = []

    def add(rtype, name, import_id, prefix):
        ident = tf_id(prefix, name, used.setdefault(rtype, set()))
        blocks.append(f"import {{\n  to = {rtype}.{ident}\n  id = {hcl(import_id)}\n}}\n")

    for am in found["auth-methods"]:
        t, key = am_type(am)
        n = am["auth_method_name"]
        t = t or OTHER_AM_RESOURCE.get(key)
        if t is None:
            report.append(f"- auth method `{n}` ({key}): no Terraform resource for this type - not exported")
            continue
        add(f"akeyless_auth_method_{t}", n, n, "am")
    for r in found["roles"]:
        n = r["role_name"]
        add("akeyless_role", n, n, "role")
        for asc in r.get("role_auth_methods_assoc") or []:
            am = asc.get("auth_method_name")
            add("akeyless_associate_role_auth_method", f"{n}__{am}", f"{n}:{am}", "assoc")
    for f in found["folders"]:
        n = "/" + f["folder_name"].strip("/")
        add("akeyless_folder", n, n, "folder")
    for cf in found["custom-fields"]:
        add("akeyless_account_custom_field", f"{cf['name']}_{cf.get('object_type', '')}", str(cf["id"]), "cf")
    for p in found["key-policies"]:
        add("akeyless_policy_keys", p["path"], str(p["id"]), "policy")
    for i in found["pki-issuers"]:
        add("akeyless_pki_cert_issuer", i["item_name"], i["item_name"], "issuer")
    if found["account-settings"]:
        add("akeyless_account_settings", "account_settings", "account-settings", "acct")

    with open(os.path.join(d, "providers.tf"), "w") as fh:
        fh.write('''# Generated by watchover export --hcl.
# Login: the provider reads AKEYLESS_ACCESS_ID / AKEYLESS_ACCESS_KEY from the environment
# when no login block is configured (read-only identity recommended).
terraform {
  required_version = ">= 1.7.0"
  required_providers {
    akeyless = {
      source  = "akeyless-community/akeyless"
      version = "~> 2.0"
    }
  }
}

variable "akeyless_api" {
  type    = string
  default = "https://api.akeyless.io"
}

provider "akeyless" {
  api_gateway_address = var.akeyless_api
}
''')
    with open(os.path.join(d, "imports.tf"), "w") as fh:
        fh.write("# Generated by watchover export --hcl. Run:\n"
                 "#   terraform init && terraform plan -generate-config-out=generated.tf\n"
                 "# Terraform reads every object and writes its resource block into generated.tf.\n\n"
                 + "\n".join(blocks))
    report.append(f"- hcl: {len(blocks)} import block(s) in hcl/imports.tf")
    report.append("- generated.tf: sensitive values (OIDC client secrets, API access keys, K8s private keys) cannot "
                  "be read back - replace them with variables before applying; review every block, then either keep "
                  "the plain resources or move them into the YAML model")

    if not a.generate:
        report.append("- next: cd hcl && terraform init && terraform plan -generate-config-out=generated.tf")
        return
    if shutil.which(a.terraform) is None:
        raise RuntimeError(f"--generate: '{a.terraform}' not found on PATH")
    if os.path.exists(os.path.join(d, "generated.tf")):
        raise RuntimeError("hcl/generated.tf already exists - delete it first (terraform will not overwrite it)")
    for cmd in ([a.terraform, "init", "-input=false"],
                [a.terraform, "plan", "-input=false", "-generate-config-out=generated.tf"]):
        print("+ " + " ".join(cmd) + f"   (in {d})", flush=True)
        rc = subprocess.run(cmd, cwd=d).returncode
        if rc != 0 and cmd[1] == "init":
            raise RuntimeError("terraform init failed")
        if rc != 0:
            report.append("- terraform plan returned an error: generated.tf may still have been written - fix the "
                          "reported attributes (often secrets or conflicting arguments) and plan again")
    if os.path.exists(os.path.join(d, "generated.tf")):
        report.append("- hcl/generated.tf written by Terraform")


if __name__ == "__main__":
    main()
