def gen_doc(name: str) -> str:
    md = open(os.path.join(REPO, "docs", name + ".md"), encoding="utf-8").read()

    def link(m):
        text, target = m.group(1), m.group(2)
        if re.match(r"https?://", target):
            return m.group(0)
        base = target.split("#")[0]
        if base.endswith(".md") and "/" not in base and os.path.splitext(base)[0] in DOCS + ["usage-guide", "README"]:
            stem = os.path.splitext(base)[0]
            return f"[{text}](#doc-{'kit-commands' if stem == 'usage-guide' else stem})"
        path = os.path.normpath(os.path.join("docs", target)).replace(os.sep, "/")
        return f"[{text}]({GITHUB}{path})"

    md = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, md)
    n = 0

    def diagram(m):                      # mermaid -> PDF figure rendered by render_diagrams()
        nonlocal n
        n += 1
        DIAGRAMS[f"{name}-{n}"] = m.group(1)
        # wide left-to-right flowcharts are printed rotated on their own page, so the labels stay legible
        path = f"generated/img/{name}-{n}.png"
        if re.match(r"\s*(flowchart|graph)\s+LR", m.group(1)):
            return ("```{=latex}\n\\begin{figure}[p]\\centering\n\\includegraphics[angle=90,width=\\textwidth,"
                    f"height=0.88\\textheight]{{{path}}}\n\\caption{{Diagram from docs/{name}.md}}\n\\end{{figure}}\n```")
        return f"![]({path}){{width=100%}}"

    md = re.sub(r"```mermaid\n(.*?)```", diagram, md, flags=re.S)
    md = re.sub(r"^# (.+)$", r"# \1 {#doc-" + name + "}", md, count=1, flags=re.M)
    md = re.sub(r"^# (?!.*\{#doc-)", "## ", md, flags=re.M)        # extra top-level headings become sections
    res = subprocess.run(["pandoc", "-f", "gfm+attributes+raw_attribute", "-t", "latex", "--top-level-division=chapter",
                          "--no-highlight", "--wrap=preserve", "--id-prefix=" + name + "-",
                          "--lua-filter=" + os.path.join(HERE, "table-widths.lua")],
                         input=md, capture_output=True, text=True, check=True)
    out = res.stdout.replace(r"\hypertarget{" + name + "-doc-" + name + "}", r"\hypertarget{doc-" + name + "}")
    out = out.replace(r"\label{" + name + "-doc-" + name + "}", r"\label{doc-" + name + "}")
    out = re.sub(r"\\hyperref\[" + re.escape(name) + r"-doc-", r"\\hyperref[doc-", out)
    out = out.replace("\\begin{verbatim}", "\\begin{Verbatim}[fontsize=\\footnotesize,breaklines,breakanywhere,"
                      "frame=leftline,framerule=1.2pt,rulecolor=\\color{wo-rule},xleftmargin=6pt]")
    out = out.replace("\\end{verbatim}", "\\end{Verbatim}")
    return HEADER + f"% source: docs/{name}.md\n" + out


DIAGRAMS: dict[str, str] = {}


def render_diagrams() -> None:
    """Mermaid blocks of docs/*.md -> PNG (SVG text labels: the PDF route squeezes HTML labels)."""
    img = os.path.join(GEN, "img")
    os.makedirs(img, exist_ok=True)
    tmp = tempfile.mkdtemp(prefix="wo-mmd-")
    cfg = os.path.join(tmp, "config.json")
    write(cfg, json.dumps({"flowchart": {"htmlLabels": False}, "themeVariables": {"fontFamily": "DejaVu Sans"}}))
    pup = os.path.join(tmp, "puppeteer.json")
    write(pup, json.dumps({"args": ["--no-sandbox"]}))
    for key, src in DIAGRAMS.items():
        write(os.path.join(tmp, key + ".mmd"), src)
        cmd = ["mmdc", "-i", os.path.join(tmp, key + ".mmd"), "-o", os.path.join(img, key + ".png"),
               "-c", cfg, "-s", "3", "-b", "white"]
        if subprocess.run(cmd, capture_output=True).returncode != 0:   # e.g. Chromium as root needs --no-sandbox
            subprocess.run(cmd + ["-p", pup], check=True, capture_output=True)
    shutil.rmtree(tmp, ignore_errors=True)


