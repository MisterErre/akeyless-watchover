#!/usr/bin/env python3
"""Build the akeyless-watchover technical reference (LaTeX -> PDF).

docs/manual/manual.tex is a short frame (overview, set-up, appendices). Everything about the commands
is generated from the code, so the reference cannot drift from it:

  generated/skill.tex       skill command catalogue  (SKILL_COMMANDS, SKILL_HOW in scripts/watchover.py
                            + one example session per command in sessions/<command>.tex)
  generated/kit.tex         kit command catalogue    (TOOLS, TOOL_HOW, TOOL_EXITS + each command's argparse options)
  generated/examples/*.tex  one short real execution per kit command, run in a sandbox copy of the repository;
                            commands that need Akeyless run against docs/manual/demo/akeyless (a stand-in CLI
                            answering from the test fixtures) and a local stand-in REST endpoint
  generated/variables.tex   Terraform input variables (terraform/ and bootstrap/)

Usage (from the repository root):
  python3 docs/manual/build.py                 # generate, run the examples, compile docs/akeyless-watchover-manual.pdf
  python3 docs/manual/build.py --skip-examples # keep the committed example executions
  python3 docs/manual/build.py --no-pdf        # generate the .tex parts only
  python3 docs/manual/build.py --check         # exit 1 if the generated catalogue/variables are out of date

Needs: Python 3.10+ with pyyaml, latexmk + XeLaTeX (TeX Live); for the examples terraform or tofu, jq, curl, zip.
"""
