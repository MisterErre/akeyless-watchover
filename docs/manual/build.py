#!/usr/bin/env python3
"""Build the akeyless-watchover manual (LaTeX -> PDF).

The manual is one LaTeX document, docs/manual/manual.tex. Hand-written chapters live in
docs/manual/chapters/. The parts that must never drift from the code are generated into
docs/manual/generated/ by this script:

  commands.tex     every skill command and kit command with ALL options (from scripts/watchover.py)
  examples/*.tex   a real execution of every kit command, run in a sandbox copy of the repository;
                   commands that need Akeyless run against docs/manual/demo/akeyless (a stand-in CLI
                   answering from the test fixtures) and a local stand-in REST endpoint
  variables.tex    Terraform input variables and outputs (terraform/ and bootstrap/)
  docs/*.tex       the Markdown documents in docs/ converted with pandoc (single source: the .md files)

Usage (from the repository root):
  python3 docs/manual/build.py                 # generate everything, compile docs/akeyless-watchover-manual.pdf
  python3 docs/manual/build.py --no-pdf        # generate the .tex parts only
  python3 docs/manual/build.py --skip-examples # keep the committed example executions (no sandbox run)
  python3 docs/manual/build.py --check         # exit 1 if commands/variables/docs .tex are out of date

Needs: Python 3.10+ with pyyaml, pandoc >= 2.11, latexmk + XeLaTeX (TeX Live), and for the examples
terraform or tofu, jq and curl.
"""
