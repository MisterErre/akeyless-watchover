def generated_static() -> dict[str, str]:
    return {os.path.join(GEN, "skill.tex"): gen_skill(), os.path.join(GEN, "kit.tex"): gen_kit(),
            os.path.join(GEN, "variables.tex"): gen_variables(),
            os.path.join(GEN, "version.tex"): HEADER + f"\\newcommand{{\\woversion}}{{{wo.VERSION}}}\n"}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-pdf", action="store_true", help="generate the .tex parts only")
    ap.add_argument("--skip-examples", action="store_true", help="keep the committed example executions")
    ap.add_argument("--check", action="store_true", help="fail if the generated catalogue/variables are stale")
    ap.add_argument("--tool", default=None, help="terraform or tofu (default: whichever is installed)")
    a = ap.parse_args(argv)

    static = generated_static()
    if a.check:
        stale = []
        for path, text in static.items():
            cur = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if cur != text:
                stale.append(os.path.relpath(path, REPO))
                sys.stdout.writelines(list(difflib.unified_diff(cur.splitlines(True), text.splitlines(True),
                                                                os.path.relpath(path, REPO), "regenerated", n=1))[:40])
        if stale:
            print("stale: " + ", ".join(stale) + "\nrun: python3 docs/manual/build.py", file=sys.stderr)
            return 1
        print("reference sources are current")
        return 0

    for path, text in static.items():
        write(path, text)
    if not a.skip_examples:
        iac = a.tool or ("tofu" if shutil.which("tofu") else "terraform")
        sb = Sandbox(iac)
        try:
            ex = examples(sb)
        finally:
            sb.close()
        names = [t.name for t in wo.TOOLS] + ["help"]
        missing = [n for n in names if n not in ex]
        if missing:
            raise SystemExit(f"no example execution for: {missing}")
        shutil.rmtree(os.path.join(GEN, "examples"), ignore_errors=True)
        for n in names:
            write(os.path.join(GEN, "examples", n + ".tex"), render_runs(ex[n]))
    print("generated", os.path.relpath(GEN, REPO))
    if a.no_pdf:
        return 0
    build = tempfile.mkdtemp(prefix="wo-latex-")
    try:
        res = subprocess.run(["latexmk", "-xelatex", "-interaction=nonstopmode", "-halt-on-error",
                              f"-outdir={build}", "manual.tex"], cwd=HERE, capture_output=True, text=True)
        if res.returncode != 0:
            log = os.path.join(build, "manual.log")
            tail = open(log, encoding="utf-8", errors="replace").read()[-4000:] if os.path.exists(log) else res.stdout[-4000:]
            print(tail, file=sys.stderr)
            return 1
        shutil.copy(os.path.join(build, "manual.pdf"), PDF)
    finally:
        shutil.rmtree(build, ignore_errors=True)
    print("built", os.path.relpath(PDF, REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
