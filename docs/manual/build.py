def options_table(p: argparse.ArgumentParser, name: str) -> str:
    rows = wo._params(p)  # noqa: SLF001 - same rows as the terminal help
    if not rows:
        return "No options.\n\n"
    o = ["\\paragraph{Options}\\leavevmode\n{\\small\n\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.27\\linewidth}"
         ">{\\raggedright\\arraybackslash}p{0.17\\linewidth}>{\\raggedright\\arraybackslash}p{0.13\\linewidth}"
         ">{\\raggedright\\arraybackslash}p{0.35\\linewidth}@{}}\n\\toprule\n"
         "\\textbf{Option} & \\textbf{Value} & \\textbf{Required / default} & \\textbf{Description} \\\\ \\midrule\\endhead\n"]
    for flag, value, req, desc in rows:
        req_tex = r"\textbf{required}" if req == "required" else (r"\emph{repeatable}" if req == "repeatable" else md_inline(req))
        o.append(f"{code(flag)} & {code(value) if value != '-' else '--'} & {req_tex} & {md_inline(desc)} \\\\\n")
    o.append("\\bottomrule\n\\end{longtable}}\n\n")
    return "".join(o)


