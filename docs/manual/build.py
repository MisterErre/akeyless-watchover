# ------------------------------------------------------------------------------------------- helpers
_TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
        "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "<": r"\textless{}", ">": r"\textgreater{}",
        "|": r"\textbar{}"}


def tex(s: str) -> str:
    """Escape plain text for LaTeX ('--' stays two hyphens instead of becoming an en dash)."""
    return "".join(_TEX.get(c, c) for c in str(s)).replace("--", "-{}-")


def code(s: str) -> str:
    """Inline code that may break at / - _ = , and |."""
    out = tex(s)
    for ch in ("/", "-", ",", "="):
        out = out.replace(ch, ch + r"\allowbreak{}")
    out = out.replace(r"\_", r"\_\allowbreak{}").replace(r"\textbar{}", r"\textbar{}\allowbreak{}")
    return r"\texttt{" + out + "}"


def md_inline(s: str) -> str:
    """Escape text that may contain `code` spans."""
    parts = re.split(r"`([^`]+)`", s)
    return "".join(code(p) if i % 2 else tex(p) for i, p in enumerate(parts))


def label(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


