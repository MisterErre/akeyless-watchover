# ------------------------------------------------------------------------------------------- helpers
_TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
        "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "<": r"\textless{}", ">": r"\textgreater{}",
        "|": r"\textbar{}"}


def tex(s: str) -> str:
    """Escape plain text for LaTeX ('--' stays two hyphens instead of becoming an en dash)."""
    return "".join(_TEX.get(c, c) for c in str(s)).replace("--", r"\mbox{-}\mbox{-}")


def code(s: str) -> str:
    """Inline code that may break at / - _ = , and |."""
    out = tex(s)
    for ch in ("/", "-", ",", "="):
        out = out.replace(ch, ch + r"\allowbreak{}")
    out = out.replace(r"\_", r"\_\allowbreak{}").replace(r"\textbar{}", r"\textbar{}\allowbreak{}")
    return r"\texttt{" + out + "}"


def md_inline(s: str) -> str:
    """Escape text that may contain `code` spans."""
    parts = re.split(r"`([^`]+)`", s)
    return "".join(code(p) if i % 2 else tex(p) for i, p in enumerate(parts))


def label(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


HEADER = "% GENERATED by docs/manual/build.py - do not edit; change the source it names instead.\n"

# ------------------------------------------------------------------------------------------- catalogues
def _how(items: list[str]) -> str:
    if not items:
        return ""
    return "\\begin{itemize}[nosep,leftmargin=1.2em]\n" + "".join(f"\\item {md_inline(h)}\n" for h in items) + "\\end{itemize}\n"


def gen_skill() -> str:
    o = [HEADER + "% source: scripts/watchover.py (SKILL_COMMANDS, SKILL_HOW) and docs/manual/sessions/*.tex\n",
         "\\chapter{Skill commands}\\label{ch:skill}\n",
         "Typed to an AI agent that has the skill (Chapter~\\ref{ch:setup}). Syntax: "
         "\\texttt{akeyless-watchover <command> [args]}, the agent's own skill syntax, or the MCP prompt "
         "\\texttt{watchover-<command>}. Arguments are free text; a plain-language request is mapped to the "
         "closest command. Every command ends with the verification that applies and the VERIFY caveats "
         "that touch the answer. Example answers are abridged and vary with the agent and model.\n\n"]
    for c in wo.SKILL_COMMANDS:
        o.append(f"\\section{{\\texttt{{{c.name}}}}}\\label{{skill:{c.name}}}\n")
        o.append("\\begin{woentry}\n")
        o.append(f"\\refrow{{Syntax}}{{{code('akeyless-watchover ' + c.name + ' ' + c.args)}}}\n")
        o.append(f"\\refrow{{Does}}{{{md_inline(c.purpose)}}}\n")
        o.append(f"\\refrow{{Delivers}}{{{md_inline(c.delivers)}}}\n")
        o.append(f"\\refrow{{How}}{{{_how(wo.SKILL_HOW.get(c.name, []))}}}\n")
        o.append("\\end{woentry}\n")
        o.append(f"\\IfFileExists{{sessions/{c.name}.tex}}{{\\input{{sessions/{c.name}.tex}}}}{{}}\n\n")
    return "".join(o)


def gen_kit() -> str:
    o = [HEADER + "% source: scripts/watchover.py (TOOLS, TOOL_HOW, TOOL_EXITS) and each command's argparse parser\n",
         "\\chapter{Kit commands}\\label{ch:kit}\n",
         "Run in the governance repository (or \\texttt{template/} of an installed skill): "
         "\\texttt{scripts/watchover <command> [options]}; \\texttt{<command> --help} or "
         "\\texttt{help <command>} prints the entry in the terminal. \\emph{Live} commands call Akeyless; "
         "the others are offline. Each entry ends with a real execution (Section~\\ref{sec:examples}).\n\n"]
    for t in wo.TOOLS:
        p = t.parser()
        o.append(f"\\section{{\\texttt{{{t.name}}}}}\\label{{kit:{t.name}}}\n")
        o.append("\\begin{woentry}\n")
        o.append(f"\\refrow{{Synopsis}}{{{code('scripts/watchover ' + t.name + ' [options]')}"
                 f"\\hfill\\emph{{{'live' if t.needs_akeyless else 'offline'}}}}}\n")
        o.append(f"\\refrow{{Does}}{{{md_inline(t.summary)}}}\n")
        o.append(f"\\refrow{{How}}{{{_how(wo.TOOL_HOW.get(t.name, []))}}}\n")
        o.append(f"\\refrow{{Exit codes}}{{{md_inline(wo.TOOL_EXITS.get(t.name, '-'))}}}\n")
        if t.env:
            o.append("\\refrow{Environment}{" + "\\newline ".join(f"{code(k)}: {md_inline(v)}" for k, v in t.env) + "}\n")
        o.append("\\end{woentry}\n")
        o.append(options_table(p, t.name))
        o.append("\\paragraph{Examples}\\leavevmode\n\\begin{Verbatim}[fontsize=\\footnotesize,breaklines,breakanywhere]\n")
        o += [e + "\n" for e in t.examples]
        o.append("\\end{Verbatim}\n")
        o.append(f"\\paragraph{{Sample run}}\\leavevmode\n\\input{{generated/examples/{t.name}.tex}}\n\n")
    hp = argparse.ArgumentParser(prog="watchover help")
    hp.add_argument("topic", nargs="?", help="a kit command name or 'skill'; omitted = overview")
    hp.add_argument("--markdown", action="store_true", help="print this reference as Markdown (docs/usage-guide.md)")
    o.append("\\section{\\texttt{help} and \\texttt{version}}\\label{kit:help}\n\\begin{woentry}\n"
             "\\refrow{Synopsis}{\\texttt{scripts/watchover help [topic] [--markdown]}; "
             "\\texttt{scripts/watchover version}\\hfill\\emph{offline}}\n"
             "\\refrow{Does}{Prints the overview, one command's entry, the skill commands, or this reference as "
             "Markdown; \\texttt{version} prints the version. No argument = \\texttt{help}.}\n\\end{woentry}\n")
    o.append(options_table(hp, "help"))
    o.append("\\paragraph{Sample run}\\leavevmode\n\\input{generated/examples/help.tex}\n\n")
    return "".join(o)


def options_table(p: argparse.ArgumentParser, name: str) -> str:
    rows = wo._params(p)  # noqa: SLF001 - same rows as the terminal help
    if not rows:
        return "No options.\n\n"
    o = ["{\\small\n\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.27\\linewidth}"
         ">{\\raggedright\\arraybackslash}p{0.17\\linewidth}>{\\raggedright\\arraybackslash}p{0.13\\linewidth}"
         ">{\\raggedright\\arraybackslash}p{0.35\\linewidth}@{}}\n\\toprule\n"
         "\\textbf{Option} & \\textbf{Value} & \\textbf{Required / default} & \\textbf{Description} \\\\ \\midrule\\endhead\n"]
    for flag, value, req, desc in rows:
        req_tex = r"\textbf{required}" if req == "required" else (r"\emph{repeatable}" if req == "repeatable" else md_inline(req))
        o.append(f"{code(flag)} & {code(value) if value != '-' else '--'} & {req_tex} & {md_inline(desc)} \\\\\n")
    o.append("\\bottomrule\n\\end{longtable}}\n\n")
    return "".join(o)


def _blocks(text: str, kind: str):
    for m in re.finditer(rf'^{kind} "([^"]+)" \{{\n(.*?)^\}}', text, re.S | re.M):
        yield m.group(1), m.group(2)


def _attr(body: str, key: str) -> str | None:
    m = re.search(rf"^  {key}\s*=\s*(.*)$", body, re.M)
    if not m:
        return None
    val = m.group(1).rstrip()
    if val.endswith(("({", "{", "[")):            # multi-line value: take until the matching close at indent 2
        end = re.search(r"^  [})\]]+\)?\s*$", body[m.end():], re.M)
        val = body[m.start():m.end() + (end.end() if end else 0)].split("=", 1)[1].strip()
    return val


# ------------------------------------------------------------------------------------------- variables.tex
def gen_variables() -> str:
    o = [HEADER + "% source: variable blocks in terraform/*.tf and bootstrap/*.tf\n"]
    for mod in ("terraform", "bootstrap"):
        files = sorted(f for f in os.listdir(os.path.join(REPO, mod)) if f.endswith(".tf"))
        text = "".join(open(os.path.join(REPO, mod, f), encoding="utf-8").read() + "\n" for f in files)
        o.append(f"\\paragraph{{\\texttt{{{mod}/}}}}\\leavevmode\n{{\\small\n\\begin{{longtable}}"
                 "{@{}>{\\raggedright\\arraybackslash}p{0.27\\linewidth}>{\\raggedright\\arraybackslash}p{0.2\\linewidth}"
                 ">{\\raggedright\\arraybackslash}p{0.49\\linewidth}@{}}\n\\toprule\n"
                 "\\textbf{Variable} & \\textbf{Default} & \\textbf{Purpose} \\\\ \\midrule\\endhead\n")
        for name, body in _blocks(text, "variable"):
            desc = (_attr(body, "description") or '""').strip('"').replace('\\"', '"')
            default = _attr(body, "default")
            sens = (_attr(body, "sensitive") or "false") == "true"
            d = "\\textbf{required}" if default is None else code(re.sub(r"\s+", " ", default))
            o.append(f"{code(name)} & {d}{' \\emph{(sensitive)}' if sens else ''} & {md_inline(desc) or '--'} \\\\\n")
        o.append("\\bottomrule\n\\end{longtable}}\n")
    return "".join(o)


class Sandbox:
    """A throw-away copy of the repository where the examples run, plus the demo back ends."""

    def __init__(self, iac: str):
        self.root = tempfile.mkdtemp(prefix="wo-manual-")
        self.repo = os.path.join(self.root, "akeyless-governance")
        os.makedirs(self.repo)
        subprocess.run(f"tar -C '{REPO}' --exclude=.terraform --exclude=__pycache__ --exclude=.pytest_cache "
                       f"-cf - terraform bootstrap scripts ci skill docs/*.md docs/manual "
                       f"| tar -C '{self.repo}' -xf -", shell=True, check=True)
        self.iac = iac
        live = os.path.join(self.root, "live-model")          # what the demo "account" looks like
        shutil.copytree(os.path.join(self.repo, "terraform", "model"), live)
        with open(os.path.join(live, "roles", "zz-manual-ui-change.yaml"), "w") as fh:
            fh.write("roles:\n  /governance/roles/temp-ui-grant:\n    rules:\n"
                     "      - { type: item-rule, path: /payments/checkout/prod/*, capabilities: [read] }\n"
                     "    associations:\n      - auth_method: /governance/auth/sso-entra-oidc\n"
                     "        sub_claims: { groups: [grp-everyone] }\n")
        self.env = dict(os.environ)
        self.env.update({
            "PATH": os.path.join(HERE, "demo") + os.pathsep + os.path.dirname(shutil.which(iac) or iac) + os.pathsep + self.env["PATH"],
            "DEMO_LIVE_MODEL": live, "NO_PROXY": "127.0.0.1,localhost", "no_proxy": "127.0.0.1,localhost",
            "PYTHONDONTWRITEBYTECODE": "1", "COLUMNS": "100", "TF_IN_AUTOMATION": "1"})
        self.env.pop("AKEYLESS_TOKEN", None)
        self.server = self._serve()
        self.api = f"http://127.0.0.1:{self.server.server_port}"

    def _serve(self):
        import fake_backend
        from akl_export import OPS
        by_path = {path: op for op, (_w, path, _s) in OPS.items()}

        class H(BaseHTTPRequestHandler):
            def do_POST(self):  # noqa: N802
                body = json.loads(self.rfile.read(int(self.headers["Content-Length"])) or "{}")
                path = self.path.split("/api/v2")[-1]
                if path == "/auth":
                    ok = body.get("access-type") == "jwt" and body.get("jwt") and body.get("access-id")
                    out, code = ({"token": "t-demo-0b3f9c"}, 200) if ok else ({"error": "unauthorized"}, 401)
                elif body.get("token") != "t-demo-0b3f9c":
                    out, code = {"error": "unauthorized"}, 401
                else:
                    try:
                        out, code = fake_backend.respond(by_path[path], {k: v for k, v in body.items() if k != "token"}), 200
                    except (fake_backend.NotFound, KeyError):
                        out, code = {"error": "not found"}, 404
                data = json.dumps(out).encode()
                self.send_response(code)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)

            def log_message(self, *a):
                pass

        srv = HTTPServer(("127.0.0.1", 0), H)
        threading.Thread(target=srv.serve_forever, daemon=True).start()
        return srv

    def run(self, cmd: str, max_lines: int = 60, head: int | None = None) -> tuple[str, int]:
        res = subprocess.run(["bash", "-c", cmd], cwd=self.repo, env=self.env, capture_output=True, text=True)
        out = (res.stdout + (res.stderr if res.stderr else "")).replace("\r", "")
        out = re.sub(r"\x1b\[[0-9;]*m", "", out)
        out = out.replace(self.repo, ".").replace(self.root, "<tmp>").replace(self.api, "http://127.0.0.1:8080")
        out = re.sub(r"(\d+\.\d+)s\b", "<t>s", out) if "passed in" in out else out
        lines = out.rstrip("\n").splitlines()
        if len(lines) > max_lines:
            h = head if head is not None else max_lines - 12
            t = max_lines - h
            lines = lines[:h] + [f"[... {len(lines) - h - t} lines omitted ...]"] + (lines[-t:] if t else [])
        return "\n".join(lines), res.returncode

    def close(self):
        self.server.shutdown()
        shutil.rmtree(self.root, ignore_errors=True)


def render_runs(runs) -> str:
    o = [HEADER + "% source: docs/manual/build.py EXAMPLES (executed in a sandbox copy of the repository)\n"]
    for note, display, out, rc in runs:
        if note:
            o.append(md_inline(note) + "\n")
        o.append("\\begin{terminal}\n")
        o.append("\\begin{Verbatim}[fontsize=\\scriptsize,breaklines,breakanywhere,commandchars=\\\\\\{\\}]\n")
        o.append("\\textcolor{wo-prompt}{\\$} \\textbf{" + _vb(display) + "}\n")
        o.append(_vb(out) + ("\n" if out else ""))
        o.append("\\end{Verbatim}\n")
        o.append(f"\\exitcode{{{rc}}}\n\\end{{terminal}}\n\n")
    return "".join(o)


def _vb(s: str) -> str:
    """Escape for a Verbatim block with commandchars \\{}."""
    return s.replace("\\", "\\\\").replace("{", "\\{").replace("}", "\\}")


