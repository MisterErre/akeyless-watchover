def _blocks(text: str, kind: str):
    for m in re.finditer(rf'^{kind} "([^"]+)" \{{\n(.*?)^\}}', text, re.S | re.M):
        yield m.group(1), m.group(2)


def _attr(body: str, key: str) -> str | None:
    m = re.search(rf"^  {key}\s*=\s*(.*)$", body, re.M)
    if not m:
        return None
    val = m.group(1).rstrip()
    if val.endswith(("({", "{", "[")):            # multi-line value: take until the matching close at indent 2
        end = re.search(r"^  [})\]]+\)?\s*$", body[m.end():], re.M)
        val = body[m.start():m.end() + (end.end() if end else 0)].split("=", 1)[1].strip()
    return val


def gen_variables() -> str:
    o = [HEADER + "% source: terraform/*.tf and bootstrap/*.tf (variable and output blocks)\n"]
    for mod, title in (("terraform", "Governance root module (\\texttt{terraform/})"),
                       ("bootstrap", "Bootstrap module (\\texttt{bootstrap/})")):
        files = sorted(f for f in os.listdir(os.path.join(REPO, mod)) if f.endswith(".tf"))
        text = "".join(open(os.path.join(REPO, mod, f), encoding="utf-8").read() + "\n" for f in files)
        o.append(f"\\section{{{title}}}\n\\subsection*{{Input variables}}\n")
        for name, body in _blocks(text, "variable"):
            desc = (_attr(body, "description") or '""').strip('"').replace('\\"', '"')
            typ = _attr(body, "type") or "any"
            default = _attr(body, "default")
            sens = (_attr(body, "sensitive") or "false") == "true"
            req = r"\textbf{required}" if default is None else "default " + code(default)
            o.append(f"\\paragraph{{{code(name)}}} {req}{' -- \\emph{sensitive}' if sens else ''}.\\\\\n{md_inline(desc) or '--'}\n")
            if "\n" in typ:
                o.append("\\begin{Verbatim}[fontsize=\\footnotesize]\n" + typ + "\n\\end{Verbatim}\n")
            else:
                o.append(f"\\\\Type: {code(typ)}\n")
        outs = list(_blocks(text, "output"))
        if outs:
            o.append("\\subsection*{Outputs}\n\\begin{tabularx}{\\linewidth}{@{}l>{\\raggedright\\arraybackslash}X@{}}\n\\toprule\n")
            for name, body in outs:
                d = (_attr(body, "description") or '"--"').strip('"')
                o.append(f"{code(name)} & {md_inline(d)} \\\\\n")
            o.append("\\bottomrule\n\\end{tabularx}\n")
    return "".join(o)


